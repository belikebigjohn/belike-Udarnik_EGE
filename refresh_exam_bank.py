    add(6, 'text', 'Уберите из предложения лишнее слово и запишите его.\nПосле экскурсии дети вернулись обратно в школу.', 'обратно', 'Глагол «вернулись» уже обозначает движение назад.')
    add(7, 'text', 'Исправьте ошибку в форме выделенного слова и запишите правильную форму.\n1) несколько НОСКОВ\n2) пара ЧУЛКОВ\n3) много ЯБЛОК\n4) опытные ИНЖЕНЕРЫ\n5) два СТУЛА', 'чулок', 'Родительный падеж множественного числа: пара чулок.')
